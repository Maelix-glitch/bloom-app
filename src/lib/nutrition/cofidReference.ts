/**
 * Nutrition — the UK CoFID reference set (M-229).
 *
 * Bloom's library is not USDA-only (owner directive, 2026-11-23): a food
 * may ship from another genuine source when it is honestly labelled and
 * licence-clean. This set carries paneer from McCance and Widdowson's
 * Composition of Foods Integrated Dataset (CoFID) — the UK national
 * food-composition database, published by Public Health England under the
 * Open Government Licence v3.0 — because USDA FoodData Central has no
 * paneer entry and the Indian IFCT paneer row is licence-restricted until
 * ICMR-NIN grants written permission. Generated by
 * `scripts/nutrition-cofid-reference.mjs` from the official CoFID 2021
 * workbook and shipped as app data; every entry is read through the strict
 * N1 parser, exactly like the USDA set, and the licence gate in
 * `usdaReference.ts` resolves the `cofid` provenance kind to the
 * registry's `uk-cofid-2021` source.
 */

import {
  COFID_REFERENCE_FOODS_RAW,
  COFID_REFERENCE_FINGERPRINT,
  COFID_REFERENCE_RETRIEVED_ON,
  COFID_REFERENCE_VERSION,
} from "./data/cofidReferenceData";
import { parseFoodList } from "./parse";
import type { Food } from "./types";

export { COFID_REFERENCE_FINGERPRINT, COFID_REFERENCE_RETRIEVED_ON, COFID_REFERENCE_VERSION };

/** The CoFID reference foods, parsed. Stable order: the generator's curation. */
export const COFID_REFERENCE_FOODS: readonly Food[] = parseFoodList(COFID_REFERENCE_FOODS_RAW);

export function findCofidReference(id: string): Food | null {
  return COFID_REFERENCE_FOODS.find((f) => f.id === id) ?? null;
}

/**
 * The data-version line shown wherever a CoFID reference food's provenance
 * is displayed: the source, the release its values came from, and the date
 * Bloom retrieved the set — e.g. "UK CoFID · McCance and Widdowson's
 * Composition of Foods Integrated Dataset · 2021 update · retrieved
 * 2026-11-23". Null for anything that is not a CoFID reference food.
 */
export function cofidDataStamp(food: Food): string | null {
  if (food.provenance.kind !== "cofid") return null;
  return [
    "UK CoFID",
    "McCance and Widdowson's Composition of Foods Integrated Dataset",
    "2021 update",
    `retrieved ${COFID_REFERENCE_RETRIEVED_ON}`,
  ].join(" · ");
}

/**
 * The dataset-level version line (audit #29), mirroring
 * `usdaDatasetVersionLine`: the dataset, its licence, when Bloom retrieved
 * it, and the shipped set's fingerprint in short form. Built only from the
 * generator-stamped record, so the line can never claim a version the data
 * does not carry.
 */
export function cofidDatasetVersionLine(): string {
  const v = COFID_REFERENCE_VERSION;
  return [
    `${v.dataset} reference set`,
    v.licence,
    `retrieved ${v.retrievedOn}`,
    `fingerprint ${v.fingerprint.slice(0, 8)}`,
  ].join(" · ");
}
