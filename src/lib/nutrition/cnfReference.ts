/**
 * Nutrition — the Canadian Nutrient File reference set (M-230).
 *
 * Bloom's library is not USDA-only (owner directive, 2026-11-23): a food
 * may ship from another genuine source when it is honestly labelled and
 * licence-clean. M-230's wave — healthy, high-protein foods only — takes
 * three foods from the Canadian Nutrient File (CNF), Health Canada's
 * national food-composition database, published through the Government of
 * Canada's open data portal under the Open Government Licence – Canada
 * v2.0: quark, kefir and an unsweetened fortified soy beverage. Every
 * shipped row carries CNF Food Source Code 37 — Health Canada's own CNF
 * Sampling and Analysis Program (SNAP-CAN). Rows the CNF republishes from
 * the USDA (its source code 0, "based on data from USDA: no changes") are
 * never shipped from this set: natto, lupins, amaranth, spirulina and
 * broad beans exist in the CNF only as USDA data, and a USDA value under
 * a Canadian label would be a mislabelled value.
 *
 * Generated by `scripts/nutrition-cnf-reference.mjs` from the official
 * CNF CSV files and shipped as app data; every entry is read through the
 * strict N1 parser, exactly like the USDA set, and the licence gate in
 * `usdaReference.ts` resolves the `cnf` provenance kind to the registry's
 * `ca-cnf-2026` source.
 */

import {
  CNF_REFERENCE_FOODS_RAW,
  CNF_REFERENCE_FINGERPRINT,
  CNF_REFERENCE_RETRIEVED_ON,
  CNF_REFERENCE_VERSION,
} from "./data/cnfReferenceData";
import { parseFoodList } from "./parse";
import type { Food } from "./types";

export { CNF_REFERENCE_FINGERPRINT, CNF_REFERENCE_RETRIEVED_ON, CNF_REFERENCE_VERSION };

/** The CNF reference foods, parsed. Stable order: the generator's curation. */
export const CNF_REFERENCE_FOODS: readonly Food[] = parseFoodList(CNF_REFERENCE_FOODS_RAW);

export function findCnfReference(id: string): Food | null {
  return CNF_REFERENCE_FOODS.find((f) => f.id === id) ?? null;
}

/**
 * The data-version line shown wherever a CNF reference food's provenance
 * is displayed: the source, the publisher, the release its values came
 * from, and the date Bloom retrieved the set — e.g. "Canadian Nutrient
 * File · Health Canada · 2026 files · retrieved 2026-11-23". Null for
 * anything that is not a CNF reference food.
 */
export function cnfDataStamp(food: Food): string | null {
  if (food.provenance.kind !== "cnf") return null;
  return [
    "Canadian Nutrient File",
    "Health Canada",
    "2026 files",
    `retrieved ${CNF_REFERENCE_RETRIEVED_ON}`,
  ].join(" · ");
}

/**
 * The dataset-level version line (audit #29), mirroring
 * `usdaDatasetVersionLine`: the dataset, its licence, when Bloom retrieved
 * it, and the shipped set's fingerprint in short form. Built only from the
 * generator-stamped record, so the line can never claim a version the data
 * does not carry.
 */
export function cnfDatasetVersionLine(): string {
  const v = CNF_REFERENCE_VERSION;
  return [
    `${v.dataset} reference set`,
    v.licence,
    `retrieved ${v.retrievedOn}`,
    `fingerprint ${v.fingerprint.slice(0, 8)}`,
  ].join(" · ");
}
