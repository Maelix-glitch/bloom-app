/**
 * Nutrition — the Australian AFCD reference set (M-230).
 *
 * Bloom's library is not USDA-only (owner directive, 2026-11-23): a food
 * may ship from another genuine source when it is honestly labelled and
 * licence-clean. M-230's wave — healthy, high-protein foods only — takes
 * six foods from the Australian Food Composition Database (AFCD),
 * Release 3, the Australian national food-composition database published
 * by Food Standards Australia New Zealand (FSANZ) under its Data User
 * Licence Agreement (modelled on CC BY-SA 3.0 AU): lupin splits, broad
 * beans, split peas, amaranth, chia seeds and flaxseed. Every shipped row
 * carries AFCD Derivation "Analysed" — the majority of its data from
 * Australian laboratory analysis — and a field AFCD's sampling notes
 * attribute to another database (vitamin C for lupin splits and broad
 * beans) is omitted rather than shipped under an AFCD label. AFCD
 * publishes energy in kilojoules only; the kcal figures are the pinned
 * kJ values divided by 4.184 and rounded, re-derived by the generator's
 * check. FSANZ's licence asks this to travel with the data: this data is
 * based on Australian data, and Australian data may not be appropriate
 * for use in other countries.
 *
 * Generated by `scripts/nutrition-afcd-reference.mjs` from the official
 * AFCD Release 3 workbook and shipped as app data; every entry is read
 * through the strict N1 parser, exactly like the USDA set, and the
 * licence gate in `usdaReference.ts` resolves the `afcd` provenance kind
 * to the registry's `au-afcd-release-3` source.
 */

import {
  AFCD_REFERENCE_FOODS_RAW,
  AFCD_REFERENCE_FINGERPRINT,
  AFCD_REFERENCE_RETRIEVED_ON,
  AFCD_REFERENCE_VERSION,
} from "./data/afcdReferenceData";
import { parseFoodList } from "./parse";
import type { Food } from "./types";

export { AFCD_REFERENCE_FINGERPRINT, AFCD_REFERENCE_RETRIEVED_ON, AFCD_REFERENCE_VERSION };

/** The AFCD reference foods, parsed. Stable order: the generator's curation. */
export const AFCD_REFERENCE_FOODS: readonly Food[] = parseFoodList(AFCD_REFERENCE_FOODS_RAW);

export function findAfcdReference(id: string): Food | null {
  return AFCD_REFERENCE_FOODS.find((f) => f.id === id) ?? null;
}

/**
 * The data-version line shown wherever an AFCD reference food's provenance
 * is displayed: the source, the release its values came from, and the date
 * Bloom retrieved the set — e.g. "Australian AFCD · Australian Food
 * Composition Database · Release 3 · retrieved 2026-11-23". Null for
 * anything that is not an AFCD reference food.
 */
export function afcdDataStamp(food: Food): string | null {
  if (food.provenance.kind !== "afcd") return null;
  return [
    "Australian AFCD",
    "Australian Food Composition Database",
    "Release 3",
    `retrieved ${AFCD_REFERENCE_RETRIEVED_ON}`,
  ].join(" · ");
}

/**
 * The dataset-level version line (audit #29), mirroring
 * `usdaDatasetVersionLine`: the dataset, its licence, when Bloom retrieved
 * it, and the shipped set's fingerprint in short form. Built only from the
 * generator-stamped record, so the line can never claim a version the data
 * does not carry.
 */
export function afcdDatasetVersionLine(): string {
  const v = AFCD_REFERENCE_VERSION;
  return [
    `${v.dataset} reference set`,
    v.licence,
    `retrieved ${v.retrievedOn}`,
    `fingerprint ${v.fingerprint.slice(0, 8)}`,
  ].join(" · ");
}
